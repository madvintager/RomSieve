using RomSieve.App.Abstractions;
using RomSieve.App.ViewModels;
using RomSieve.Core.Models;
using RomSieve.Core.Services;
using RomSieve.Core.Tests.Fixtures;

namespace RomSieve.App.Tests;

/// <summary>
/// Convention of the MAME software lists in the interface: offered in the list, recognized from the DAT of a list
/// (SabreTools DAT or hash file of MAME), shown by its badge, saved; the Filters page shows the No-Intro / Redump options
/// with the dump quality and the categories a software never carries greyed, and the MAME card reduced; the Languages
/// page has an order of its own, which follows the region mode; the preview puts a software in the folder of its list.
/// </summary>
public sealed class SoftwareListViewModelTests : IDisposable
{
    private readonly TempDirectoryFixture _tmp = new();
    private readonly CoreTestServices _services = new();

    public void Dispose() => _tmp.Dispose();

    private DirectoriesViewModel CreateDirectories() =>
        new(_services.I18n, new HeadlessDialogService(), _services.DatService, _services.NoIntroParser, _services.Organizer, _services.MameParser, TimeSpan.Zero);

    private string WriteSabreToolsDat() => _tmp.WriteText("megadriv.xml", """
        <?xml version="1.0" encoding="utf-8"?>
        <datafile>
        	<header>
        		<name>megadriv</name>
        		<description>Sega Mega Drive/Genesis cartridges</description>
        		<version>0.289</version>
        		<author>Pleasuredome</author>
        		<comment>Generated by SabreTools 1.2.1</comment>
        	</header>
        	<machine name="sonic">
        		<description>Sonic The Hedgehog (Europe, USA)</description>
        		<year>1991</year>
        		<publisher>Sega</publisher>
        		<rom name="MPR-13913-F.ic1" size="524288" crc="f9394e97"/>
        	</machine>
        </datafile>
        """);

    private string WriteHashFile() => _tmp.WriteText("hash.xml", """
        <?xml version="1.0"?>
        <!DOCTYPE softwarelist SYSTEM "softwarelist.dtd">
        <softwarelist name="megadriv" description="Sega Mega Drive/Genesis cartridges">
        	<software name="sonic">
        		<description>Sonic The Hedgehog (Europe, USA)</description>
        		<year>1991</year>
        		<publisher>Sega</publisher>
        		<part name="cart" interface="megadriv_cart"><dataarea name="rom" size="524288"><rom name="MPR-13913-F.ic1" size="524288" crc="f9394e97"/></dataarea></part>
        	</software>
        	<software name="sonicj" cloneof="sonic">
        		<description>Sonic The Hedgehog (Japan, Korea)</description>
        		<year>1991</year>
        		<publisher>Sega</publisher>
        		<part name="cart" interface="megadriv_cart"><dataarea name="rom" size="524288"><rom name="mpr-13933 w33.ic1" size="524288" crc="afe05eee"/></dataarea></part>
        	</software>
        </softwarelist>
        """);

    [Theory]
    [InlineData(false)]
    [InlineData(true)]
    public async Task DatOfAList_ShouldBeDetectedAndShownByItsBadge(bool hashFile)
    {
        var directories = CreateDirectories();

        directories.DatFilePath = hashFile ? WriteHashFile() : WriteSabreToolsDat();

        // Known from the first games, before the whole DAT is read
        directories.DetectedDatConvention.Should().Be(NamingConvention.MameSoftwareList);
        await directories.DatLoadTask;
        directories.DetectedDatConvention.Should().Be(NamingConvention.MameSoftwareList);
        directories.EffectiveConvention.Should().Be(NamingConvention.MameSoftwareList);
        directories.ConventionBadgeText.Should().Be(_services.I18n.Tr("tab1.badge_softlist_detected"));
        directories.ConventionBadgeTone.Should().Be("Mame");
        directories.DatCloneRelations.Should().Be(hashFile ? DatCloneRelations.Present : DatCloneRelations.None);

        // The files of the MAME machines (CHD folder, categories, ratings) say nothing of a software
        directories.IsMameConvention.Should().BeFalse();
    }

    // A folder of DATs of two software lists
    private string WriteDatFolder()
    {
        foreach (var list in new[] { "megadriv", "gamegear" })
        {
            _tmp.WriteText(Path.Combine("lists", list + ".xml"), $"""
                <?xml version="1.0"?>
                <datafile>
                	<header><name>{list}</name><description>{list} cartridges</description></header>
                	<machine name="sonic"><description>Sonic The Hedgehog (Europe, USA)</description><year>1991</year><publisher>Sega</publisher><rom name="{list}.ic1" size="16" crc="f9394e97"/></machine>
                </datafile>
                """);
        }

        return _tmp.GetFilePath("lists");
    }

    [Fact]
    public async Task FolderOfDats_ShouldBeChosenAndSummedUpByItsLists()
    {
        var vm = TestMainViewModel.Create(new HeadlessDialogService { NextPickedFolder = WriteDatFolder() }, _tmp.GetFilePath("config.json"));
        var directories = vm.Directories;

        await directories.BrowseDatFolderAsync();
        await directories.DatLoadTask;

        directories.DatFilePath.Should().Be(_tmp.GetFilePath("lists"));
        directories.EffectiveConvention.Should().Be(NamingConvention.MameSoftwareList);
        directories.ConventionBadgeText.Should().Be(_services.I18n.Tr("tab1.badge_softlist_detected"));
        directories.DatInfoTone.Should().Be("Ok");
        directories.DatInfoText.Should().Be(_services.I18n.Tr(
            "tab1.dat_info_summary_lists", ("name", "lists"), ("lists", 2), ("games", 2), ("count", 2)));

        // A folder is a DAT like a file for the steps: neither missing nor in error
        vm.Navigation.CollectionEntry.IndicatorText.Should().NotBe(_services.I18n.Tr("nav.state_dat_not_found"));
    }

    [Fact]
    public async Task FolderOfDats_ThatIsNoFolderOfSoftwareLists_ShouldSayWhy()
    {
        var folder = WriteDatFolder();
        _tmp.WriteText(Path.Combine("lists", "snes.xml"), """
            <?xml version="1.0"?>
            <datafile><header><name>Nintendo - Super Nintendo Entertainment System</name><homepage>No-Intro</homepage></header>
            <game name="Super Game (Europe)"><rom name="Super Game (Europe).sfc" size="4" crc="12345678"/></game></datafile>
            """);
        var directories = CreateDirectories();

        directories.DatFilePath = folder;
        await directories.DatLoadTask;

        directories.DatInfoTone.Should().Be("Error");
        directories.DatInfoText.Should().Be(_services.I18n.Tr("dat.folder_not_software_list", ("file", "snes.xml")));
    }

    [Fact]
    public void SoftwareListConvention_ShouldBeOfferedAndSaved()
    {
        var directories = CreateDirectories();

        directories.NamingConventionOptions.Select(o => o.Value).Should().Contain(NamingConvention.MameSoftwareList);
        directories.SelectedNamingConvention = NamingConvention.MameSoftwareList;
        directories.ConventionBadgeText.Should().Be(_services.I18n.Tr("tab1.badge_softlist"));

        var settings = new SortSettings();
        directories.WriteTo(settings);
        var data = new Dictionary<string, object?>();
        SortSettingsSerializer.Write(settings, data);
        data["naming_convention"].Should().Be("mame_softlist");
        SortSettingsSerializer.Read(data).NamingConvention.Should().Be(NamingConvention.MameSoftwareList);
    }

    [Fact]
    public void FiltersPage_ShouldShowTheNoIntroOptionsWithWhatASoftwareNeverCarriesGreyed()
    {
        var vm = TestMainViewModel.Create(new HeadlessDialogService(), _tmp.GetFilePath("config.json"));
        var filters = vm.Filters;

        filters.ShowConvention(NamingConvention.MameSoftwareList);

        filters.ShownConventionIndex.Should().Be(FiltersViewModel.NoIntroConventionIndex);
        filters.NoIntroConventionLabel.Should().Be(_services.I18n.Tr("filters.convention_nointro_mame"));
        filters.AreSoftwareListOptionsShown.Should().BeTrue();
        filters.AreMameOptionsShown.Should().BeFalse("the options of the machines do not apply to a software");
        filters.IsMameCardShown.Should().BeTrue("the card stays in sight, reduced to its title");
        filters.MameCardHint.Should().Be(_services.I18n.Tr("filters.mame_card_softlist_hint"));
        filters.IsMultidiskGroupShown.Should().BeTrue("its complete sets option applies to the software");

        filters.IsDumpQualityApplicable.Should().BeFalse();
        filters.DumpsNoEffectText.Should().Be(_services.I18n.Tr("filters.dumps_no_effect_softlist"));
        filters.AreNoIntroOnlyOptionsApplicable.Should().BeFalse();
        filters.UnlicensedTooltip.Should().Be(_services.I18n.Tr("filters.tooltip_no_effect_softlist_category"));
        filters.AreTranslationsApplicable.Should().BeTrue("the lists mark their translations");
        filters.TranslationsTooltip.Should().Be(_services.I18n.Tr("filters.tooltip_keep_nointro_translations"));

        // Back to No-Intro: everything applies again
        filters.ShowConvention(NamingConvention.NoIntro);
        filters.AreSoftwareListOptionsShown.Should().BeFalse();
        filters.IsDumpQualityApplicable.Should().BeTrue();
        filters.NoIntroConventionLabel.Should().Be(_services.I18n.Tr("filters.convention_nointro"));
        filters.MameCardHint.Should().Be(_services.I18n.Tr("filters.mame_card_inactive_hint"));
    }

    [Fact]
    public async Task LanguagesPage_ShouldShowTheOrderOfTheSoftwareOfTheDat()
    {
        var vm = TestMainViewModel.Create(new HeadlessDialogService(), _tmp.GetFilePath("config.json"));

        vm.Directories.DatFilePath = WriteHashFile();
        await vm.Directories.DatLoadTask;

        var priorities = vm.Priorities;
        priorities.ShownOrderConvention.Should().Be(NamingConvention.MameSoftwareList);
        priorities.IsSoftwareListOrderShown.Should().BeTrue();
        priorities.ShownCriteriaOrder.Should().BeSameAs(priorities.SoftwareListCriteriaOrder);
        priorities.CriteriaOrders.Should().Contain(priorities.SoftwareListCriteriaOrder);
        priorities.SoftwareListCriteriaOrder.Order.Should().Equal(TiebreakOrder.Default(NamingConvention.MameSoftwareList));

        // The DAT has parents: the parent / clone criterion may decide
        priorities.SoftwareListCriteriaOrder.Items.Single(i => i.Criterion == TiebreakCriterion.ParentClone).HasNoEffect.Should().BeFalse();
        priorities.SoftwareListCriteriaOrder.Items.Single(i => i.Criterion == TiebreakCriterion.DriverStatus).Description
            .Should().Be(_services.I18n.Tr("tiebreak.tooltip_driver_status_mame_softlist"));
        priorities.SoftwareListCriteriaOrder.LeftOutText.Should().Contain(_services.I18n.Tr("tab3.tiebreak_convention_mame_softlist"));
    }

    [Fact]
    public void OrderOfTheSoftware_ShouldFollowTheRegionModeAndBeSaved()
    {
        var vm = TestMainViewModel.Create(new HeadlessDialogService(), _tmp.GetFilePath("config.json"));
        var order = vm.Priorities.SoftwareListCriteriaOrder;

        vm.Priorities.RegionPriorityMode = RegionPriorityMode.CountryFirst;
        order.Order.Should().Equal(TiebreakOrder.Default(NamingConvention.MameSoftwareList, RegionPriorityMode.CountryFirst));

        // Putting the language above the country in the order of the software sets the mode of every order but MAME
        order.SelectedItem = order.Items.Single(i => i.Criterion == TiebreakCriterion.LanguageRank);
        order.MoveUpCommand.Execute(null);
        vm.Priorities.RegionPriorityMode.Should().Be(RegionPriorityMode.LanguageFirst);
        vm.Priorities.TosecCriteriaOrder.Order.Should().Equal(TiebreakOrder.Default(NamingConvention.Tosec));
        vm.Priorities.MameCriteriaOrder.Order.Should().Equal(TiebreakOrder.Default(NamingConvention.Mame));

        // Then moved by hand, and saved
        order.SelectedItem = order.Items.Single(i => i.Criterion == TiebreakCriterion.VideoStandard);
        order.MoveUpCommand.Execute(null);
        var saved = order.Order.ToList();
        vm.BuildConfigUnchecked().Filters.SoftwareListTiebreakOrder.Should().Equal(saved);

        var settings = new SortSettings();
        vm.Priorities.WriteTo(settings);
        var reread = TestMainViewModel.Create(new HeadlessDialogService(), _tmp.GetFilePath("other.json"));
        reread.Priorities.ReadFrom(settings);
        reread.Priorities.SoftwareListCriteriaOrder.Order.Should().Equal(saved);
    }

    [Fact]
    public async Task Preview_ShouldPutASoftwareInTheFolderOfItsList()
    {
        var directories = CreateDirectories();
        directories.DestinationDir = "out";
        directories.SelectedNamingConvention = NamingConvention.MameSoftwareList;
        directories.FlatDestination = true;
        await directories.Preview.WhenIdleAsync();

        var preview = directories.Preview;
        preview.CaptionText.Should().Be(_services.I18n.Tr("tab1.preview_builtin_softlist"));
        preview.Examples[0].SourceName.Should().Be("sonic.zip");
        preview.Examples[0].TargetPath.Should().Be(Path.Combine("out", "megadriv", "sonic.zip"));
        preview.HasWarning.Should().BeFalse();

        // Folders above the list: MAME would not find the software
        directories.FlatDestination = false;
        directories.Pattern = "{publisher}";
        await directories.Preview.WhenIdleAsync();
        preview.Examples[0].TargetPath.Should().Be(Path.Combine("out", "Sega", "megadriv", "sonic.zip"));
        preview.WarningText.Should().Contain(_services.I18n.Tr("tab1.preview_softlist_subfolders"));
    }
}
