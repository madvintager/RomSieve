    [Fact]
    public async Task HashFileOfMame_ShouldGiveTheParentsAndTheRomsAClonesTakesFromIt()
    {
        var catalog = await _services.DatService.ParseDatFileAsync(WriteHashFile());

        catalog.Header.Convention.Should().Be(NamingConvention.MameSoftwareList);
        catalog.Header.Name.Should().Be("megadriv");
        catalog.Header.Description.Should().Be("Sega Mega Drive/Genesis cartridges");

        // A ROM element without a name only goes on loading the previous ROM: a "continue" reads more of its file, as
        // mame -getsoftlist writes its size, a "fill" nothing; a size may be hexadecimal, a CRC lack its leading zeros
        var game = catalog.GameByName["game"];
        game.Roms.Select(r => r.Name).Should().Equal("world.u1", "shared.u2");
        game.Roms[0].Size.Should().Be(WorldProgram.Length);
        game.Roms[1].Size.Should().Be(SharedGraphics.Length);
        game.DriverStatus.Should().Be(MameDriverStatus.Good);
        catalog.GameByName["leadzero"].Roms.Single().Crc.Should().Be("08e40a86");

        var clone = catalog.GameByName["gamej"];
        clone.CloneOf.Should().Be("game");
        clone.RomOf.Should().Be("game");
        clone.DriverStatus.Should().Be(MameDriverStatus.Imperfect);
        clone.Roms.Single(r => r.Name == "shared.u2").Merge.Should().Be("shared.u2");
        clone.Roms.Single(r => r.Name == "japan.u1").Merge.Should().BeNull();
        catalog.CloneToParent.Should().ContainKey("gamej");
        catalog.GameByName["sonic"].DriverStatus.Should().Be(MameDriverStatus.Preliminary);
    }

