    private string Zip(string name, params (string Member, byte[] Data)[] members)
    {
        var path = Path.Combine(_source, name);
        using var zip = ZipFile.Open(path, ZipArchiveMode.Create);
        foreach (var (member, data) in members)
        {
            using var stream = zip.CreateEntry(member).Open();
            stream.Write(data);
        }
        return path;
    }

    private SortConfig Config(string datPath, Action<FilterConfig>? filters = null, string? source = null)
    {
        var config = new SortConfig
        {
            SourceDir = source ?? _source,
            DestinationDir = _destination,
            DatFile = datPath,
            Pattern = string.Empty,
            Filters = new FilterConfig
            {
                OneGameOneRom = true,
                PriorityLanguages = ["en"],
                PriorityCountries = ["EU", "US"],
                NoIntroExcludePirate = true
            }
        };
        filters?.Invoke(config.Filters);
        return config;
    }

