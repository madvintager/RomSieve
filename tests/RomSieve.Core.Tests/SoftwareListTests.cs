    [Fact]
    public void Settings_ShouldReadAndWriteTheOrderOfTheSoftware()
    {
        var settings = new SortSettings
        {
            SoftwareListTiebreakOrder = [TiebreakCriterion.CountryRank, .. TiebreakOrder.Default(NamingConvention.MameSoftwareList).Where(c => c != TiebreakCriterion.CountryRank)],
            NamingConvention = NamingConvention.MameSoftwareList
        };
        var data = new Dictionary<string, object?>();
        SortSettingsSerializer.Write(settings, data);

        data["naming_convention"].Should().Be("mame_softlist");
        var read = SortSettingsSerializer.Read(data);
        read.SoftwareListTiebreakOrder.Should().Equal(settings.SoftwareListTiebreakOrder);
        read.NamingConvention.Should().Be(NamingConvention.MameSoftwareList);
        SortSettingsSerializer.ToSortConfig(read).Filters.GetTiebreakOrder(NamingConvention.MameSoftwareList)
            .Should().Equal(settings.SoftwareListTiebreakOrder);

        // A file without the order (before the lists) takes the default order of its region mode
        data.Remove("tiebreak_order_softlist");
        data["region_priority_mode"] = "country_first";
        data.Remove("tiebreak_order_tosec");
        SortSettingsSerializer.Read(data).SoftwareListTiebreakOrder
            .Should().Equal(TiebreakOrder.Default(NamingConvention.MameSoftwareList, RegionPriorityMode.CountryFirst));
    }
