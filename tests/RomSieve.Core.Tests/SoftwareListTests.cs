    [Fact]
    public async Task Simulation_ShouldMakeOneItemPerSoftwareIntoTheFolderOfItsList()
    {
        CreateCollection();
        _tmp.WriteText(Path.Combine("src", "megadriv", "readme.txt"), "not a software");

        var result = await _services.Processor.ExecuteAsync(Config(WriteSabreToolsDat()));

        var sonic = Item(result.Items, "sonic.zip");
        sonic.IsWholeArchive.Should().BeTrue();
        sonic.DatGameName.Should().Be("sonic");
        sonic.TargetFilename.Should().Be(Path.Combine("megadriv", "sonic.zip"));
        sonic.Parsed.Title.Should().Be("Sonic The Hedgehog");
        sonic.Parsed.Convention.Should().Be(NamingConvention.MameSoftwareList);
        sonic.Status.Should().Be(FileStatus.Valid);
        sonic.TargetPath.Should().Be(Path.Combine(_destination, "megadriv", "sonic.zip"));

        // One version per game, by title: the Japanese release and the pirate are left out
        Item(result.Items, "sonicj.zip").Status.Should().Be(FileStatus.Excluded);
        Item(result.Items, "sonicpir.zip").Status.Should().Be(FileStatus.Excluded);

        // An archive renamed is identified by its ROM, and goes under its short name
        var renamed = Item(result.Items, "Streets of Rage 2 (E).zip");
        renamed.DatGameName.Should().Be("sor2");
        renamed.TargetFilename.Should().Be(Path.Combine("megadriv", "sor2.zip"));

        // An archive that lacks a ROM is an incomplete set
        Item(result.Items, "gunstar.zip").MameSet!.MissingRoms.Should().Be(1);

        // A loose file is no software, and nothing of the DAT is non-conforming
        Item(result.Items, "readme.txt").StatusReason!.Key.Should().Be("reason.mame_not_a_set");
        result.Items.Where(it => it.DatGameName is not null).Should().NotContain(it => it.Status == FileStatus.Unmatched);
        result.Stats.TotalScanned.Should().Be(6);
    }

