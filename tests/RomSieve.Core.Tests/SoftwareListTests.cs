    [Fact]
    public async Task HashFile_ShouldGroupTheClonesByParentAndKeepTheParentOfASplitClone()
    {
        // A split collection: the clone only holds its own ROM, the shared one is in the set of its parent
        Zip("game.zip", ("world.u1", WorldProgram), ("shared.u2", SharedGraphics));
        Zip("gamej.zip", ("japan.u1", JapanProgram));

        var log = new LogCollector();
        var result = await _services.Processor.ExecuteAsync(
            Config(WriteHashFile(), f =>
            {
                f.PriorityLanguages = ["ja"];
                f.PriorityCountries = ["JP"];
            }),
            logProgress: log);

        // Different titles, one game: the Japanese clone wins, and the parent goes with it, which MAME needs
        var clone = Item(result.Items, "gamej.zip");
        clone.Status.Should().Be(FileStatus.Valid);
        clone.MameSet!.IsSplit.Should().BeTrue();
        clone.MameSet.RequiredSets.Should().Equal("game");

